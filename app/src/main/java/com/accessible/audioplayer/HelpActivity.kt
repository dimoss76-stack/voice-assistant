package com.accessible.audioplayer

import android.os.Bundle
import android.widget.Button
import android.widget.LinearLayout
import android.widget.ScrollView
import android.widget.TextView
import androidx.appcompat.app.AppCompatActivity

class HelpActivity : AppCompatActivity() {

    override fun onCreate(savedInstanceState: Bundle?) {
        super.onCreate(savedInstanceState)
        val settings = VoiceSettings(this)

        val layout = LinearLayout(this).apply {
            orientation = LinearLayout.VERTICAL
            setPadding(60, 100, 60, 60)
        }

        val textView = TextView(this)
        textView.textSize = 20f
        textView.text = """
            КАК ПОЛЬЗОВАТЬСЯ ПОМОЩНИКОМ

            ═══════════════════════════
            1. АКТИВАЦИЯ
            ═══════════════════════════
            Скажите: «${settings.activationWord}»
            Программа ответит: «${settings.confirmWord}»
            и будет ждать команду 15 секунд.

            Если нужно отменить — скажите «отмена».


            ═══════════════════════════
            2. ЗВОНКИ
            ═══════════════════════════

            ИСХОДЯЩИЙ ЗВОНОК:
            Скажите: «${settings.activationWord}, позвони»
            Программа спросит: «Каму звонить?»
            Назовите имя контакта.
            Программа спросит: «Имя. Звонить?»
            Скажите: «да» — позвонит, «нет» — отменит.

            Если у контакта несколько номеров —
            программа спросит по очереди.

            ВХОДЯЩИЙ ЗВОНОК:
            Когда звонит телефон, программа скажет:
            «Звонит Имя. Ответить?»
            Скажите: «да» — ответит, «нет» — сбросит.

            На экране появятся большие кнопки:
            • ОТВЕТИТЬ (зелёная)
            • СБРОСИТЬ (красная)
            Можно нажать или ответить голосом.

            ЗАВЕРШЕНИЕ ЗВОНКА:
            Во время разговора скажите:
            «завершить этот звонок» — разговор завершится.

            СПИСОК КОНТАКТОВ:
            Скажите: «${settings.activationWord}, контакты»
            Программа перечислит все контакты по алфавиту.
            Скажите «стоп» — чтобы остановить.


            ═══════════════════════════
            3. ВРЕМЯ
            ═══════════════════════════
            Скажите: «${settings.activationWord}, время»
            Программа скажет текущее время.

            Также работает: «час», «сколько времени».


            ═══════════════════════════
            4. ДАТА
            ═══════════════════════════
            Скажите: «${settings.activationWord}, дата»
            Программа скажет сегодняшнюю дату.

            Также работает: «день», «число».


            ═══════════════════════════
            5. ОТМЕНА ДЕЙСТВИЯ
            ═══════════════════════════
            В любой момент, когда программа ждёт ответа
            (звонит, выбирает контакт, ждёт имя) —
            скажите: «отмена» или «стоп».

            Программа ответит: «Отменено» и вернётся
            в обычный режим.


            ═══════════════════════════
            6. ВЫКЛЮЧЕНИЕ
            ═══════════════════════════
            ${if (settings.shutdownEnabled) """
            Скажите: «${settings.shutdownWord}» — помощник выключится.
            Чтобы включить снова — откройте приложение.
            """.trimIndent() else """
            Команда выключения ОТКЛЮЧЕНА.
            Чтобы включить — зайдите в НАСТРОЙКИ
            и поставьте галочку «Разрешить выключение голосом».
            """.trimIndent()}


            ═══════════════════════════
            7. ЗВУКОВЫЕ СИГНАЛЫ
            ═══════════════════════════
            Короткий бип — программа готова слушать.
            Двойной бип — ждёт имя контакта.
            Тройной бип — ждёт «да» или «нет».
            Низкий сигнал — ошибка.


            ═══════════════════════════
            8. НАСТРОЙКИ
            ═══════════════════════════
            Через кнопку «НАСТРОЙКИ» можно:

            • Изменить ключевое слово активации.
            • Изменить слово подтверждения.
            • Включить/отключить команду выключения.
            • Выбрать расположение кнопок при звонке:
              вертикальные или горизонтальные.
            • Показать/скрыть кнопки при входящем звонке.
            • Выбрать модель распознавания.

            Слова можно вводить вручную или записывать
            голосом (кнопка с микрофоном 🎤).


            ═══════════════════════════
            ЕСЛИ ЧТО-ТО НЕ ПОНЯТНО
            ═══════════════════════════
            Попросите помощи у близких.
            Настройки и справку можно открыть
            с главного экрана приложения.
        """.trimIndent()
        layout.addView(textView)

        val btnBack = Button(this).apply {
            text = "НАЗАД"
            textSize = 20f
            setPadding(30, 50, 30, 50)
        }
        btnBack.setOnClickListener { finish() }
        layout.addView(btnBack)

        val scroll = ScrollView(this).apply { addView(layout) }
        setContentView(scroll)
    }
}
